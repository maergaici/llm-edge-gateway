package metrics

import (
	"github.com/prometheus/client_golang/prometheus"
)

var (
	HttpRequestsTotal = prometheus.NewCounterVec(
		prometheus.CounterOpts{
			Name: "http_requests_total",
			Help: "Total number of HTTP requests",
		},
		[]string{"method", "path", "status"},
	)

	HttpRequestDuration = prometheus.NewHistogramVec(
		prometheus.HistogramOpts{
			Name:    "http_request_duration_seconds",
			Help:    "HTTP request duration in seconds",
			Buckets: []float64{0.01, 0.05, 0.1, 0.5, 1, 2.5, 5},
		},
		[]string{"method", "path"},
	)

	LlmTimeToFirstToken = prometheus.NewHistogramVec(
		prometheus.HistogramOpts{
			Name:    "llm_time_to_first_token_seconds",
			Help:    "Time to first token in seconds",
			Buckets: []float64{0.1, 0.5, 1, 2, 3, 5, 10},
		},
		[]string{"model"},
	)

	LlmTotalTokensGenerated = prometheus.NewCounterVec(
		prometheus.CounterOpts{
			Name: "llm_total_tokens_generated",
			Help: "Total number of tokens generated by llm",
		},
		[]string{"model"},
	)
)

func Register() {
	prometheus.MustRegister(HttpRequestsTotal)
	prometheus.MustRegister(HttpRequestDuration)
	prometheus.MustRegister(LlmTimeToFirstToken)
	prometheus.MustRegister(LlmTotalTokensGenerated)
}
